"use client";

import Link from "next/link";
import { useRef, useState } from "react";
import { API_BASE_URL } from "../../lib/api";

const MAX_FILES = 5;
const MAX_TOTAL_SIZE = 150 * 1024 * 1024;

function formatSize(bytes: number) {
  if (bytes < 1024 * 1024) {
    return `${(bytes / 1024).toFixed(1)} KB`;
  }

  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

type TransferResponse = {
  transfer_id: string;
  share_code: string;
  upload_token: string;
  upload_deadline_at: string;
  files: {
    file_id: string;
    filename: string;
    upload_url: string;
    upload_fields: Record<string, string>;
  }[];
};

type ScanStatusResponse = {
  scan_completed: boolean;
  files: {
    file_id: string;
    filename: string;
    status:
      | "PENDING_UPLOAD"
      | "UPLOADED"
      | "SCANNING"
      | "AVAILABLE"
      | "REJECTED"
      | "FAILED"
      | "DELETED";
  }[];
  share_code?: string;
};

const SCAN_STATUS_LABELS: Record<ScanStatusResponse["files"][number]["status"], string> = {
  PENDING_UPLOAD: "Waiting for upload",
  UPLOADED: "Waiting for scan",
  SCANNING: "Scanning",
  AVAILABLE: "Safe · Available",
  REJECTED: "Rejected · Unsafe file",
  FAILED: "Scan failed",
  DELETED: "Deleted",
};

export default function SendPage() {
  const [files, setFiles] = useState<File[]>([]);
  const [error, setError] = useState("");
  const [isDragging, setIsDragging] = useState(false);
  const [notice, setNotice] = useState("");

  const [isCreating, setIsCreating] = useState(false);
  const [hasStarted, setHasStarted] = useState(false);
  const [isCompleted, setIsCompleted] = useState(false);

  const [transfer, setTransfer] = useState<TransferResponse | null>(null);
  const [scanStatus, setScanStatus] = useState<ScanStatusResponse | null>(null);

  const inputRef = useRef<HTMLInputElement>(null);
  const submissionStartedRef = useRef(false);

  const totalSize = files.reduce((sum, file) => sum + file.size, 0);

  function addFiles(incoming: FileList | File[]) {
    if (hasStarted) return;

    const combined = [...files, ...Array.from(incoming)];

    if (combined.length > MAX_FILES) {
      setError("You can select a maximum of 5 files.");
      return;
    }

    const size = combined.reduce((sum, file) => sum + file.size, 0);

    if (size > MAX_TOTAL_SIZE) {
      setError("Total file size cannot exceed 150 MB.");
      return;
    }

    setFiles(combined);
    setError("");
    setNotice("");
  }

  function removeFile(index: number) {
    if (hasStarted) return;

    setFiles((current) => current.filter((_, i) => i !== index));
    setError("");
  }

  async function uploadFiles(transferData: TransferResponse) {
    for (const [index, fileData] of transferData.files.entries()) {
      const formData = new FormData();

      // Add the fields generated by Django.
      for (const [key, value] of Object.entries(fileData.upload_fields)) {
        formData.append(key, value);
      }

      // Add the actual file.
      formData.append("file", files[index]);

      const response = await fetch(fileData.upload_url, {
        method: "POST",
        body: formData,
      });

      if (!response.ok) {
        throw new Error(
          `Upload failed for ${fileData.filename}. Status: ${response.status}`
        );
      }
    }
  }

  async function completeTransfer(transferData: TransferResponse) {
    const response = await fetch(
      `${API_BASE_URL}/transfers/${transferData.transfer_id}/complete/`,
      {
        method: "POST",
        headers: {
          "X-Upload-Token": transferData.upload_token,
        },
      }
    );

    if (!response.ok) {
      const message = await response.text();
      throw new Error(`Transfer completion failed: ${message}`);
    }

    return response.json();
  }

  async function getTransferStatus(
    transferData: TransferResponse
  ): Promise<ScanStatusResponse> {
    const response = await fetch(
      `${API_BASE_URL}/transfers/${transferData.transfer_id}/status/`,
      {
        method: "GET",
        headers: {
          "X-Upload-Token": transferData.upload_token,
        },
        cache: "no-store",
      }
    );

    if (!response.ok) {
      const message = await response.text();
      throw new Error(`Could not get scan status: ${message}`);
    }

    return response.json();
  }

  async function waitForScanCompletion(transferData: TransferResponse) {
    while (true) {
      const result = await getTransferStatus(transferData);
      setScanStatus(result);

      if (result.scan_completed) {
        if (!result.share_code) {
          throw new Error(
            "Scanning finished, but the server did not return a share code."
          );
        }
        return result;
      }

      setNotice("Your files are being scanned. This may take a moment...");
      await new Promise((resolve) => setTimeout(resolve, 2000));
    }
  }

  async function handleSend() {
    // Prevent accidental repeated submissions.
    if (submissionStartedRef.current || files.length === 0) {
      return;
    }

    submissionStartedRef.current = true;

    setHasStarted(true);
    setIsCreating(true);
    setError("");
    setNotice("");
    setTransfer(null);
    setScanStatus(null);

    try {
      // Step 1: Initialize transfer with Django.
      const response = await fetch(`${API_BASE_URL}/transfers/`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          files: files.map((file) => ({
            filename: file.name,
            size: file.size,
            content_type: file.type,
          })),
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          data.detail || data.error || "Failed to initialize transfer."
        );
      }

      setTransfer(data);

      // Step 2: Upload files directly to S3.
      setNotice("Uploading your files...");
      await uploadFiles(data);

      // Step 3: Complete transfer through Django.
      setNotice("Files uploaded. Completing transfer...");
      await completeTransfer(data);

      // Step 4: Poll Django until every file reaches a terminal scan status.
      setNotice("Transfer completed. Waiting for security scans...");
      await waitForScanCompletion(data);

      // Step 5: Reveal the share code only after scanning is complete.
      setNotice("");
      setIsCompleted(true);
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Something went wrong."
      );
    } finally {
      setIsCreating(false);
    }
  }

  async function handleCopy(value: string, label: string) {
    try {
      await navigator.clipboard.writeText(value);
      setNotice(`${label} copied successfully!`);
    } catch {
      setError(`Could not copy ${label.toLowerCase()}. Please copy it manually.`);
    }
  }

  function handleCopyLink() {
    if (!scanStatus?.share_code) return;

    const shareLink = `${window.location.origin}/receive?code=${scanStatus.share_code}`;

    handleCopy(shareLink, "Share link");
  }

  function handleNewTransfer() {
    window.location.reload();
  }

  return (
    <main className="min-h-screen bg-[#f7f6f2] px-5 py-6 text-[#171717] sm:px-10">
      <div className="mx-auto max-w-6xl">

        {/* Header */}
        <header className="flex items-center justify-between">
          <Link href="/" className="flex items-center gap-2">
            <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-black text-white">
              ↑
            </span>

            <span className="text-lg font-semibold tracking-tight">
              QuickShare
            </span>
          </Link>

          <nav className="flex items-center gap-1 rounded-full bg-[#eeede9] p-1">
            <Link
              href="/send"
              className="rounded-full bg-white px-5 py-2 text-sm shadow-sm"
            >
              Send
            </Link>

            <Link
              href="/receive"
              className="rounded-full px-5 py-2 text-sm hover:bg-white"
            >
              Receive
            </Link>
          </nav>

          <div className="w-20" />
        </header>

        {isCompleted && transfer && scanStatus?.share_code ? (
          /* SUCCESS SCREEN */
          <section className="mx-auto mt-16 max-w-xl">
            <div className="rounded-3xl border border-[#e9e8e4] bg-white p-7 text-center sm:p-10">

              <div className="mx-auto flex h-16 w-16 items-center justify-center rounded-2xl bg-[#f0efff] text-3xl text-[#5144c8]">
                ✓
              </div>

              <h1 className="mt-6 text-3xl font-semibold tracking-tight">
                Transfer created!
              </h1>

              <p className="mt-2 text-sm text-[#777670]">
                Your files have finished security scanning. You can now share
                the code with your recipient.
              </p>

              {/* Share code */}
              <div className="mt-8 rounded-2xl bg-[#f7f6f2] p-6">
                <p className="text-xs font-medium uppercase tracking-widest text-[#999890]">
                  Your share code
                </p>

                <p className="mt-3 text-4xl font-semibold tracking-[0.2em]">
                  {scanStatus.share_code}
                </p>

                <button
                  onClick={() =>
                    handleCopy(scanStatus.share_code!, "Share code")
                  }
                  className="mt-5 rounded-full bg-[#171717] px-7 py-3 text-sm font-medium text-white transition hover:bg-[#333]"
                >
                  Copy code
                </button>

                <button
                  onClick={handleCopyLink}
                  className="mt-3 block w-full rounded-full border border-[#e5e4df] bg-white px-7 py-3 text-sm font-medium transition hover:bg-[#f7f6f2]"
                >
                  Copy share link
                </button>
              </div>

              {/* Read-only file list */}
              <div className="mt-8 text-left">
                <div className="flex items-center justify-between">
                  <h2 className="text-base font-semibold">
                    Files sent
                  </h2>

                  <span className="text-xs text-[#999890]">
                    {files.length} {files.length === 1 ? "file" : "files"}
                  </span>
                </div>

                <div className="mt-4 space-y-2">
                  {files.map((file, index) => (
                    <div
                      key={`${file.name}-${index}`}
                      className="flex items-center gap-3 rounded-xl border border-[#eeede9] p-3"
                    >
                      <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-[#f4f3ef]">
                        📄
                      </div>

                      <div className="min-w-0 flex-1">
                        <p className="truncate text-sm font-medium">
                          {file.name}
                        </p>

                        <p className="mt-1 text-xs text-[#999890]">
                          {formatSize(file.size)}
                        </p>
                      </div>

                      <span
                        className={`text-xs font-medium ${
                          scanStatus.files.find(
                            (item) => item.file_id === transfer.files[index]?.file_id
                          )?.status === "AVAILABLE"
                            ? "text-green-700"
                            : scanStatus.files.find(
                                  (item) => item.file_id === transfer.files[index]?.file_id
                                )?.status === "SCANNING"
                              ? "text-[#5144c8]"
                              : "text-red-600"
                        }`}
                      >
                        {(() => {
                          const status = scanStatus.files.find(
                            (item) => item.file_id === transfer.files[index]?.file_id
                          )?.status;
                          return status ? SCAN_STATUS_LABELS[status] : "Unknown";
                        })()}
                      </span>
                    </div>
                  ))}
                </div>
              </div>

              {notice && (
                <p className="mt-4 text-center text-xs text-[#5144c8]">
                  {notice}
                </p>
              )}

              {error && (
                <p className="mt-4 text-center text-xs text-red-600">
                  {error}
                </p>
              )}

              {/* Start another transfer */}
              <div className="mt-8 border-t border-[#eeede9] pt-6">
                <p className="text-sm text-[#777670]">
                  Need to send more files?
                </p>

                <button
                  onClick={handleNewTransfer}
                  className="mt-4 w-full rounded-full bg-[#171717] px-6 py-4 text-sm font-medium text-white transition hover:bg-[#333]"
                >
                  Start a new transfer →
                </button>
              </div>
            </div>
          </section>
        ) : hasStarted && transfer ? (
          /* UPLOAD AND SCAN PROGRESS SCREEN */
          <section className="mx-auto mt-16 max-w-xl">
            <div className="rounded-3xl border border-[#e9e8e4] bg-white p-7 sm:p-10">
              <div className="mx-auto flex h-16 w-16 items-center justify-center rounded-2xl bg-[#f0efff] text-3xl text-[#5144c8]">
                {scanStatus?.scan_completed ? "✓" : "…"}
              </div>

              <h1 className="mt-6 text-center text-2xl font-semibold tracking-tight">
                {scanStatus?.scan_completed
                  ? "Security scan completed"
                  : "Preparing your transfer"}
              </h1>

              <p className="mt-2 text-center text-sm text-[#777670]">
                {notice || "Your files are being processed. Please keep this page open."}
              </p>

              <div className="mt-8 space-y-3">
                {files.map((file, index) => {
                  const fileStatus = scanStatus?.files.find(
                    (item) => item.file_id === transfer.files[index]?.file_id
                  );

                  return (
                    <div
                      key={`${file.name}-${index}`}
                      className="flex items-center gap-3 rounded-xl border border-[#eeede9] p-3"
                    >
                      <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-[#f4f3ef]">
                        📄
                      </div>
                      <div className="min-w-0 flex-1">
                        <p className="truncate text-sm font-medium">{file.name}</p>
                        <p className="mt-1 text-xs text-[#999890]">
                          {formatSize(file.size)}
                        </p>
                      </div>
                      <span className="shrink-0 text-xs font-medium text-[#5144c8]">
                        {fileStatus
                          ? SCAN_STATUS_LABELS[fileStatus.status]
                          : "Waiting..."}
                      </span>
                    </div>
                  );
                })}
              </div>

              {!scanStatus?.scan_completed && (
                <p className="mt-6 text-center text-xs text-[#999890]">
                  The share code will appear after all files finish scanning.
                </p>
              )}

              {error && (
                <p className="mt-4 text-center text-sm text-red-600">{error}</p>
              )}
            </div>
          </section>
        ) : (
          /* FILE SELECTION SCREEN */
          <>
            {/* Page heading */}
            <section className="pt-10 text-center">
              <h1 className="text-3xl font-semibold tracking-tight sm:text-4xl">
                What are you sending?
              </h1>

              <p className="mt-2 text-sm text-[#777670]">
                Add your files and get a shareable code.
              </p>
            </section>

            {/* Two-column layout */}
            <section className="mx-auto mt-8 grid max-w-5xl grid-cols-1 gap-5 md:grid-cols-2">

              {/* RIGHT: Drag and drop */}
              <div
                onDragOver={(event) => {
                  event.preventDefault();

                  if (!hasStarted) {
                    setIsDragging(true);
                  }
                }}
                onDragLeave={(event) => {
                  if (!event.currentTarget.contains(event.relatedTarget as Node)) {
                    setIsDragging(false);
                  }
                }}
                onDrop={(event) => {
                  event.preventDefault();
                  setIsDragging(false);

                  if (hasStarted) return;

                  addFiles(event.dataTransfer.files);
                }}
                className={`flex min-h-[420px] flex-col items-center justify-center rounded-3xl border-2 border-dashed p-6 text-center transition ${
                  isDragging
                    ? "border-[#5144c8] bg-[#f0efff]"
                    : "border-[#d8d7d1] bg-white"
                } ${hasStarted ? "opacity-60" : ""}`}
              >
                <div className="flex h-16 w-16 items-center justify-center rounded-2xl bg-[#f0efff] text-3xl text-[#5144c8]">
                  ↑
                </div>

                <h2 className="mt-6 text-xl font-semibold">
                  {isDragging
                    ? "Drop your files here"
                    : "Drag and drop files here"}
                </h2>

                <p className="mt-2 max-w-xs text-sm leading-relaxed text-[#777670]">
                  Drag files from your computer and drop them here, or browse
                  your device.
                </p>

                <input
                  ref={inputRef}
                  type="file"
                  multiple
                  disabled={hasStarted}
                  className="hidden"
                  onChange={(event) => {
                    if (event.target.files) {
                      addFiles(event.target.files);
                    }

                    event.target.value = "";
                  }}
                />

                <button
                  disabled={hasStarted}
                  onClick={() => inputRef.current?.click()}
                  className="mt-7 rounded-full border border-[#e5e4df] bg-white px-7 py-3 text-sm font-medium transition hover:bg-[#f7f6f2] disabled:cursor-not-allowed disabled:opacity-50"
                >
                  Browse files
                </button>

                <p className="mt-6 text-xs text-[#999890]">
                  Up to 5 files · 150 MB total
                </p>
              </div>

              {/* LEFT: Selected files */}
              <div className="flex min-h-[420px] flex-col rounded-3xl border border-[#e9e8e4] bg-white p-5 sm:p-6">

                <div className="flex items-center justify-between">
                  <h2 className="text-lg font-semibold">
                    Your files
                  </h2>

                  <span className="text-xs text-[#999890]">
                    {files.length}/{MAX_FILES}
                  </span>
                </div>

                {files.length === 0 ? (
                  <div className="flex flex-1 flex-col items-center justify-center py-12 text-center">
                    <div className="flex h-14 w-14 items-center justify-center rounded-2xl bg-[#f4f3ef]">
                      <span className="text-2xl">📁</span>
                    </div>

                    <p className="mt-4 text-sm font-medium">
                      No files selected yet
                    </p>

                    <p className="mt-1 text-xs text-[#999890]">
                      Your selected files will appear here.
                    </p>
                  </div>
                ) : (
                  <div className="mt-5 flex-1 space-y-2 overflow-y-auto">
                    {files.map((file, index) => (
                      <div
                        key={`${file.name}-${index}`}
                        className="flex items-center gap-3 rounded-xl border border-[#eeede9] p-3"
                      >
                        <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-[#f4f3ef]">
                          📄
                        </div>

                        <div className="min-w-0 flex-1">
                          <p className="truncate text-sm font-medium">
                            {file.name}
                          </p>

                          <p className="mt-1 text-xs text-[#999890]">
                            {formatSize(file.size)}
                          </p>
                        </div>

                        <button
                          disabled={hasStarted}
                          onClick={() => removeFile(index)}
                          aria-label={`Remove ${file.name}`}
                          className="shrink-0 text-lg text-[#999890] hover:text-red-600 disabled:cursor-not-allowed disabled:opacity-30"
                        >
                          ×
                        </button>
                      </div>
                    ))}
                  </div>
                )}

                {/* Summary and send */}
                <div className="mt-auto border-t border-[#eeede9] pt-5">
                  <div className="mb-4 flex items-center justify-between text-sm">
                    <span className="text-[#777670]">
                      {files.length}{" "}
                      {files.length === 1 ? "file" : "files"} selected
                    </span>

                    <span className="font-medium">
                      {formatSize(totalSize)}
                    </span>
                  </div>

                  <button
                    disabled={files.length === 0 || hasStarted}
                    onClick={handleSend}
                    className="w-full rounded-full bg-[#171717] px-6 py-4 text-sm font-medium text-white transition hover:bg-[#333] disabled:cursor-not-allowed disabled:bg-[#e4e2dc] disabled:text-[#999890]"
                  >
                    {isCreating
                      ? scanStatus
                        ? "Scanning files..."
                        : "Uploading files..."
                      : hasStarted
                        ? "Transfer started"
                        : "Send files →"}
                  </button>

                  {error && (
                    <p className="mt-3 text-center text-xs text-red-600">
                      {error}
                    </p>
                  )}

                  {notice && (
                    <p className="mt-3 text-center text-xs text-[#777670]">
                      {notice}
                    </p>
                  )}
                </div>
              </div>
            </section>
          </>
        )}
      </div>
    </main>
  );
}